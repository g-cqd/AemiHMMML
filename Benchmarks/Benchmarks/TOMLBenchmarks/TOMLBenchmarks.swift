import AemiTOML
import Benchmark
import Foundation
import TOMLDecoder

// AemiTOML beside TOMLDecoder (pure Swift, TOML 1.1) on the same bytes. `parse` builds each library's document; `materialize`
// reads every value (AemiTOML walks its views; TOMLDecoder converts to `[String: Any]`, its own full read). Throughput is per
// document: divide the file's size by the time for MB/s.

/// TOMLDecoder's corpus from its checkout (the classic JSON benchmark files, as TOML), and a generated Cargo.lock, the shape of
/// configuration TOML: many small tables, short strings, arrays of tables.
private func corpus() -> [(name: String, bytes: [UInt8])] {
    let checkout = URL(fileURLWithPath: #filePath)  // Benchmarks/Benchmarks/TOMLBenchmarks/TOMLBenchmarks.swift
        .deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
        .appendingPathComponent(".build/checkouts/TOMLDecoder/Sources/Resources/fixtures")
    var files: [(String, [UInt8])] = [("cargo-lock", cargoLock(packages: 2000))]
    for name in ["twitter", "canada"] {
        if let data = FileManager.default.contents(atPath: checkout.appendingPathComponent(name + ".toml").path) {
            files.append((name, Array(data)))
        }
    }
    return files
}

private func cargoLock(packages: Int) -> [UInt8] {
    var text = "# This file is automatically @generated by Cargo.\nversion = 4\n"
    for index in 0 ..< packages {
        text += """

            [[package]]
            name = "crate-\(index)"
            version = "\(index % 7).\(index % 13).\(index % 5)"
            source = "registry+https://github.com/rust-lang/crates.io-index"
            checksum = "\(String(repeating: String(index % 16, radix: 16), count: 64))"
            dependencies = [
             "crate-\((index * 31) % packages)",
             "crate-\((index * 17) % packages) \(index % 3).0.0",
            ]

            """
    }
    return Array(text.utf8)
}

/// Every value of an AemiTOML document read: strings decoded, numbers and dates materialised.
private func walk(_ value: TOMLValue) -> Int {
    switch value.kind {
        case .table, .array: value.elements.reduce(value.count) { $0 &+ walk($1) }
        case .string: value.string?.utf8.count ?? 0
        case .integer: Int(truncatingIfNeeded: value.integer ?? 0)
        case .float: value.double.map { $0.isFinite ? Int($0.truncatingRemainder(dividingBy: 1024)) : 1 } ?? 0
        case .boolean: value.bool == true ? 1 : 0
        default: value.dateTime?.second ?? 0
    }
}

nonisolated(unsafe) let benchmarks = {
    Benchmark.defaultConfiguration = .init(
        metrics: [.wallClock, .cpuTotal, .instructions, .mallocCountTotal, .peakMemoryResident],
        maxDuration: .seconds(3)
    )
    for (name, bytes) in corpus() {
        Benchmark("toml/parse/\(name)/AemiTOML") { benchmark in
            for _ in benchmark.scaledIterations {
                blackHole(try? TOMLDocument(parsing: bytes))
            }
        }
        Benchmark("toml/parse/\(name)/TOMLDecoder") { benchmark in
            for _ in benchmark.scaledIterations {
                blackHole(try? TOMLTable(source: bytes))
            }
        }
        Benchmark("toml/materialize/\(name)/AemiTOML") { benchmark in
            for _ in benchmark.scaledIterations {
                if let document = try? TOMLDocument(parsing: bytes) { blackHole(walk(document.root)) }
            }
        }
        Benchmark("toml/materialize/\(name)/TOMLDecoder") { benchmark in
            for _ in benchmark.scaledIterations {
                if let table = try? TOMLTable(source: bytes) { blackHole(try? [String: Any](table)) }
            }
        }
    }
}
